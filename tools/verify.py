#!/usr/bin/env python3
"""Checks the whole project in a few seconds, without Android Studio.   Usage:  python3 tools/verify.py [--quick]

 1. package names match their folders and no old names are left
 2. every R.raw / R.font / R.drawable / R.mipmap / R.string reference exists
 3. manifest + XML files are well-formed and their @references exist
 4. every `import ng.name.nsikak.kidquest.*` points at something that really exists
 5. icons exist at every density with the right sizes; Bible assets are complete
 6. (needs kotlinc) the Kotlin code parses, the pure game logic compiles and ALL unit tests run
Set KOTLINC=/path/to/kotlinc if it is not on PATH. Step 6 is skipped (with a note) when there is none."""
import glob, os, re, shutil, subprocess, sys, tempfile
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG = "ng.name.nsikak.kidquest"
MAIN = os.path.join(ROOT, "app/src/main"); RES = os.path.join(MAIN, "res")
fails, notes = [], []
def ok(msg): print("  ok   ", msg)
def bad(msg): fails.append(msg); print("  FAIL ", msg)
def note(msg): notes.append(msg); print("  note ", msg)
def read(p): return open(p, encoding="utf-8").read()
kt_files = [p for p in glob.glob(ROOT + "/app/src/**/*.kt", recursive=True)]

print("1. names and packages")
for p in kt_files:
    m = re.search(r"^package\s+([\w.]+)", read(p), re.M)
    want = os.path.relpath(os.path.dirname(p), ROOT).split("java/")[-1].replace("/", ".")
    if not m or m.group(1) != want: bad(f"{os.path.relpath(p, ROOT)}: package {m and m.group(1)} != folder {want}")
left = [p for p in glob.glob(ROOT + "/**/*", recursive=True)
        if os.path.isfile(p) and p.endswith((".kt", ".kts", ".xml", ".toml", ".md")) and ".git/" not in p
        and re.search(r"version5|Version5|Version 5", read(p))]
(bad(f"old names left in {left}") if left else ok("no old 'version5' names left"))
gradle = read(ROOT + "/app/build.gradle.kts")
(ok(f"namespace + applicationId = {PKG}") if gradle.count(f'"{PKG}"') >= 2 else bad("namespace/applicationId not set to " + PKG))

print("2. resource references")
res_names = {"raw": set(), "font": set(), "drawable": set(), "mipmap": set(), "string": set(), "color": set()}
for d in os.listdir(RES):
    kind = d.split("-")[0]
    if kind in res_names and os.path.isdir(os.path.join(RES, d)):
        for f in os.listdir(os.path.join(RES, d)): res_names[kind].add(os.path.splitext(f)[0])
for f in glob.glob(RES + "/values*/*.xml"):
    for el in ET.parse(f).getroot():
        if el.tag in ("string", "color"): res_names[el.tag].add(el.get("name"))
used = set()
for p in kt_files:
    if "/test/" in p or "/androidTest/" in p: continue
    for kind, name in re.findall(r"\bR\.(raw|font|drawable|mipmap|string|color)\.(\w+)", read(p)): used.add((kind, name))
missing = [f"R.{k}.{n}" for k, n in sorted(used) if n not in res_names[k]]
(bad(f"missing resources: {missing}") if missing else ok(f"{len(used)} R.* references all exist"))

print("3. manifest and XML")
xml_files = glob.glob(MAIN + "/**/*.xml", recursive=True)
for f in xml_files:
    try: ET.parse(f)
    except ET.ParseError as e: bad(f"{os.path.relpath(f, ROOT)}: {e}")
ok(f"{len(xml_files)} XML files are well-formed")
man = read(MAIN + "/AndroidManifest.xml")
for kind, name in re.findall(r"@(mipmap|drawable|string|style|xml)/([\w.]+)", man):
    if kind == "style":
        if not re.search(r'name="%s"' % re.escape(name), read(RES + "/values/themes.xml")): bad(f"manifest style {name} not defined")
    elif kind == "xml":
        if not os.path.exists(f"{RES}/xml/{name}.xml"): bad(f"manifest @xml/{name} missing")
    elif name not in res_names.get(kind, set()): bad(f"manifest @{kind}/{name} missing")
for perm in re.findall(r'uses-permission android:name="([\w.]+)"', man): ok(f"permission {perm}")
ok("manifest references resolve")

print("4. imports resolve")
decl = {}   # package -> set of top-level names
for p in kt_files:
    t = read(p); pk = re.search(r"^package\s+([\w.]+)", t, re.M).group(1)
    names = re.findall(r"^(?:(?:private|internal|public|const|sealed|data|enum|annotation|inline|value)\s+)*(?:class|object|interface|fun|val|var|typealias)\s+(?:<[^>]+>\s*)?(?:[\w.]+\.)?(\w+)", t, re.M)
    decl.setdefault(pk, set()).update(names)
    for owner in re.findall(r"^(?:enum class|class|object|sealed interface|interface)\s+(\w+)", t, re.M): decl[pk].add(owner)
n_imports = 0
for p in kt_files:
    for imp in re.findall(r"^import\s+(ng\.name\.nsikak\.kidquest[\w.]*)(?:\s+as\s+\w+)?$", read(p), re.M):
        n_imports += 1
        pk, _, name = imp.rpartition(".")
        if name == "*" or imp == PKG + ".R": continue   # R is generated by the build
        if name not in decl.get(pk, set()):
            # nested member, e.g. import pkg.Outer.Inner
            outer_pk, _, outer = pk.rpartition(".")
            if outer not in decl.get(outer_pk, set()): bad(f"{os.path.relpath(p, ROOT)}: import {imp} not found")
ok(f"{n_imports} project imports checked")

print("5. assets")
dens = {"mdpi": (48, 108), "hdpi": (72, 162), "xhdpi": (96, 216), "xxhdpi": (144, 324), "xxxhdpi": (192, 432)}
try:
    from PIL import Image
    for d, (icon, fg) in dens.items():
        for name, size in (("ic_launcher.png", icon), ("ic_launcher_round.png", icon), ("ic_launcher_foreground.png", fg), ("ic_launcher_monochrome.png", fg)):
            p = f"{RES}/mipmap-{d}/{name}"
            if not os.path.exists(p): bad(f"missing {os.path.relpath(p, ROOT)}")
            elif Image.open(p).size != (size, size): bad(f"{name} in {d} should be {size}px")
    ok("launcher icons present at all 5 densities with correct sizes")
except ImportError:
    note("Pillow not installed: icon sizes not checked")
for f in ("mipmap-anydpi-v26/ic_launcher.xml", "mipmap-anydpi-v26/ic_launcher_round.xml", "drawable-nodpi/ic_launcher_background.png"):
    (ok if os.path.exists(f"{RES}/{f}") else bad)(f"icon file {f}")
kjv = MAIN + "/assets/bibles/kjv"
(ok("KJV: index + 66 book files") if all(os.path.exists(f"{kjv}/{i:02d}.json") for i in range(1, 67)) and os.path.exists(kjv + "/index.json") else bad("KJV files incomplete"))
big = [os.path.relpath(f, ROOT) for f in glob.glob(MAIN + "/**/*", recursive=True) if os.path.isfile(f) and os.path.getsize(f) > 600_000]
(note(f"large files: {big}") if big else ok("no unexpectedly large files"))
bad_fmt = [os.path.relpath(p, ROOT) for p in kt_files if re.search(r'"%0?\d*d[^"]*"\.format|String\.format\(', read(p))]
(bad(f"locale-dependent formatting in {bad_fmt}") if bad_fmt else ok("no locale-dependent number formatting"))


# ---------- helpers for steps 7 and 8: a tiny Kotlin "cleaner" (drops comments, flattens string literals) ----------
def clean(src):
    out, i, n = [], 0, len(src)
    while i < n:
        c = src[i]
        if src.startswith("//", i):
            while i < n and src[i] != "\n": i += 1
        elif src.startswith("/*", i):
            j = src.find("*/", i + 2); i = n if j < 0 else j + 2
        elif src.startswith('"""', i):
            j = src.find('"""', i + 3); i = n if j < 0 else j + 3; out.append('"S"')
        elif c == '"':
            i += 1; depth = 0
            while i < n:
                ch = src[i]
                if depth == 0:
                    if ch == "\\": i += 2; continue
                    if ch == '"': i += 1; break
                    if src.startswith("${", i): depth = 1; i += 2; continue
                else:
                    if ch == '"':   # nested string inside a template
                        i += 1
                        while i < n and src[i] != '"':
                            i += 2 if src[i] == "\\" else 1
                    elif ch == "{": depth += 1
                    elif ch == "}": depth -= 1
                i += 1
            out.append('"S"')
        elif c == "'" and i + 2 < n and (src[i + 2] == "'" or (src[i + 1] == "\\" and src[i + 3:i + 4] == "'")):
            i += 3 if src[i + 2] == "'" else 4; out.append("'c'")
        else:
            out.append(c); i += 1
    return "".join(out)

def balanced(text, start):
    """text[start] is '('. Returns (inside, index_after_close) or None."""
    depth, i = 0, start
    while i < len(text):
        ch = text[i]
        if ch in "([{": depth += 1
        elif ch in ")]}":
            depth -= 1
            if depth == 0: return text[start + 1:i], i + 1
        i += 1
    return None

def split_top(text):
    parts, depth, cur, angle = [], 0, [], 0
    for ch in text:
        if ch in "([{": depth += 1
        elif ch in ")]}": depth -= 1
        if ch == "," and depth == 0: parts.append("".join(cur)); cur = []
        else: cur.append(ch)
    tail = "".join(cur)
    if tail.strip(): parts.append(tail)
    return [p.strip() for p in parts if p.strip()]

print("7. calls to project functions use real parameter names")
cleaned = {p: clean(read(p)) for p in kt_files}
sigs = {}   # name -> list of signatures; each signature = list of (param, has_default)
for p, t in cleaned.items():
    for m in re.finditer(r"\bfun\s+(?:<[^>]*>\s*)?(?:[\w.<>?]+\.)?(\w+)\s*\(", t):
        got = balanced(t, m.end() - 1)
        if not got: continue
        params = []
        for part in split_top(got[0]):
            part = re.sub(r"^(?:@\w+(?:\([^)]*\))?\s*)*", "", part)
            part = re.sub(r"^(?:vararg|noinline|crossinline)\s+", "", part)
            pm = re.match(r"(\w+)\s*:", part)
            if pm: params.append((pm.group(1), "=" in part.split(":", 1)[1] and re.search(r"(?<![=!<>])=(?!=)", part) is not None))
        sigs.setdefault(m.group(1), []).append(params)
unique = {k: v[0] for k, v in sigs.items() if len(v) == 1}
n_calls, problems = 0, []
for p, t in cleaned.items():
    for m in re.finditer(r"(?<![\w.])([A-Za-z_]\w*)\s*\(", t):
        name = m.group(1)
        if name not in unique: continue
        if re.search(r"\b%s\s*:\s*\(" % name, t): continue   # a lambda parameter with the same name, not the declared function
        before = t[max(0, m.start() - 12):m.start()]
        if re.search(r"\bfun\s+(?:<[^>]*>\s*)?$", before) or re.search(r"\b(?:class|object|interface)\s+$", before): continue
        got = balanced(t, m.end() - 1)
        if not got: continue
        params = unique[name]; names = [x[0] for x in params]
        args = split_top(got[0]); trailing = bool(re.match(r"\s*\{", t[got[1]:got[1] + 4]))
        n_calls += 1
        provided, positional = set(), 0
        for a in args:
            nm = re.match(r"(\w+)\s*=(?!=)", a)
            if nm:
                if nm.group(1) not in names: problems.append(f"{os.path.relpath(p, ROOT)}: {name}(...) has no parameter '{nm.group(1)}'")
                provided.add(nm.group(1))
            else:
                if positional < len(names): provided.add(names[positional])
                else: problems.append(f"{os.path.relpath(p, ROOT)}: {name}(...) given too many arguments")
                positional += 1
        if trailing and names: provided.add(names[-1])
        missing = [x for x, d in params if not d and x not in provided]
        if missing: problems.append(f"{os.path.relpath(p, ROOT)}: {name}(...) is missing {missing}")
for pr in sorted(set(problems)): bad(pr)
if not problems: ok(f"{n_calls} calls to {len(unique)} project functions all match their declarations")

print("8. every library symbol a file uses is imported there")
known = {}   # simple name -> set of import paths seen anywhere in the project
for p in kt_files:
    for imp in re.findall(r"^import\s+([\w.]+)(?:\s+as\s+\w+)?$", read(p), re.M):
        if imp.startswith(("androidx.", "android.", "kotlin.", "kotlinx.", "java.")): known.setdefault(imp.rsplit(".", 1)[1], set()).add(imp)
_ki = os.path.join(ROOT, "tools", "known_imports.txt")
if os.path.exists(_ki):
    for line in read(_ki).splitlines():
        line = line.strip()
        if line and not line.startswith("#"): known.setdefault(line.rsplit(".", 1)[1], set()).add(line)
ambient = {"String", "Int", "Long", "Float", "Double", "Boolean", "List", "Map", "Set", "Unit", "Any", "Nothing", "Pair", "Exception",
           "Math", "IllegalStateException", "Regex", "Char", "ArrayList", "HashMap", "HashSet", "LinkedHashMap", "LinkedHashSet", "Array",
           "Enum", "Comparable", "Throwable", "Deprecated", "Suppress", "JvmStatic", "OptIn", "Locale", "TimeZone"}
miss = []
for p, t in cleaned.items():
    own = set(re.findall(r"\b(?:fun|class|object|interface|val|var|enum class)\s+(?:<[^>]*>\s*)?(?:[\w.]+\.)?(\w+)", t))
    imported = {i.rsplit(".", 1)[1] for i in re.findall(r"^import\s+([\w.]+)", read(p), re.M)}
    siblings = decl.get(re.search(r"^package\s+([\w.]+)", read(p), re.M).group(1), set())
    for name in known:
        if name in imported or name in own or name in ambient or name in siblings: continue
        pat = r"(?<![\w.])%s\b" % name if name[0].isupper() else r"(?<![\w.])%s\s*[({]" % name
        if re.search(pat, t): miss.append(f"{os.path.relpath(p, ROOT)} uses '{name}' without importing it (e.g. {sorted(known[name])[0]})")
for m_ in sorted(set(miss)): bad(m_)
if not miss: ok("no missing imports detected")
for p, t in cleaned.items():
    for ext in re.findall(r"\d\.(dp|sp)\b", t):
        if ext not in {i.rsplit('.', 1)[1] for i in re.findall(r"^import\s+([\w.]+)", read(p), re.M)}:
            bad(f"{os.path.relpath(p, ROOT)} uses .{ext} without importing androidx.compose.ui.unit.{ext}")

print("6. Kotlin build and unit tests")
kotlinc = os.environ.get("KOTLINC") or shutil.which("kotlinc")
if "--quick" in sys.argv: note("--quick: skipped the Kotlin steps")
elif not kotlinc: note("kotlinc not found: skipped. Set KOTLINC=/path/to/kotlinc (https://github.com/JetBrains/kotlin/releases) to enable the unit tests")
else:
    out = tempfile.mkdtemp()
    ui = [p for p in kt_files if "/test/" not in p and "/androidTest/" not in p]
    r = subprocess.run([kotlinc, "-nowarn", "-d", out + "/all"] + ui, capture_output=True, text=True)
    errs = [l for l in (r.stdout + r.stderr).splitlines() if "error:" in l]
    syntax = [l for l in errs if re.search(r"expecting|unexpected|unclosed|missing '|syntax|illegal", l, re.I)]
    (bad("syntax errors:\n    " + "\n    ".join(syntax[:8])) if syntax else ok(f"all {len(ui)} source files parse (the other {len(errs)} messages only say Android/Compose libraries are absent here)"))
    core = glob.glob(MAIN + "/java/ng/name/nsikak/kidquest/core/*.kt")
    tests = glob.glob(ROOT + "/app/src/test/**/*.kt", recursive=True)
    shim = glob.glob(ROOT + "/tools/shim/*.kt")
    r = subprocess.run([kotlinc, "-nowarn", "-d", out + "/t"] + shim + core + tests, capture_output=True, text=True)
    if r.returncode != 0: bad("core/tests do not compile:\n" + (r.stdout + r.stderr)[:1500])
    else:
        std = os.path.join(os.path.dirname(os.path.dirname(os.path.realpath(kotlinc))), "lib", "kotlin-stdlib.jar")
        r = subprocess.run(["java", "-cp", f"{out}/t:{std}", "RunnerKt"], capture_output=True, text=True, cwd=ROOT + "/app")
        lines = r.stdout.strip().splitlines()
        for l in lines:
            if l.startswith("FAIL"): bad(l)
        (ok if r.returncode == 0 else bad)("unit tests: " + (lines[-1] if lines else r.stderr[:300]))
    shutil.rmtree(out, ignore_errors=True)

print()
for n in notes: print("NOTE:", n)
print("RESULT:", "ALL GOOD" if not fails else f"{len(fails)} PROBLEM(S)")
sys.exit(1 if fails else 0)
